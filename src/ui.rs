use tiny_skia::{Color, FillRule, Paint, PathBuilder, Pixmap, Rect, Stroke, Transform};

pub fn paint_rgba(c: [u8; 4]) -> Paint<'static> {
    let mut p = Paint::default();
    p.set_color(Color::from_rgba8(c[0], c[1], c[2], c[3]));
    p.anti_alias = true;
    p
}

pub fn fill_solid_rect(pix: &mut Pixmap, x: f32, y: f32, w: f32, h: f32, col: [u8; 4]) {
    if let Some(rect) = Rect::from_xywh(x, y, w, h) {
        pix.fill_rect(rect, &paint_rgba(col), Transform::identity(), None);
    }
}

pub fn rounded_rect_path(x: f32, y: f32, w: f32, h: f32, r: f32) -> Option<tiny_skia::Path> {
    let r = r.min(w * 0.5).min(h * 0.5);
    let mut pb = PathBuilder::new();
    pb.move_to(x + r, y);
    pb.line_to(x + w - r, y);
    pb.quad_to(x + w, y, x + w, y + r);
    pb.line_to(x + w, y + h - r);
    pb.quad_to(x + w, y + h, x + w - r, y + h);
    pb.line_to(x + r, y + h);
    pb.quad_to(x, y + h, x, y + h - r);
    pb.line_to(x, y + r);
    pb.quad_to(x, y, x + r, y);
    pb.close();
    pb.finish()
}

pub fn draw_rounded_rect(pix: &mut Pixmap, x: f32, y: f32, w: f32, h: f32, r: f32, col: [u8; 4]) {
    if let Some(path) = rounded_rect_path(x, y, w, h, r) {
        pix.fill_path(&path, &paint_rgba(col), FillRule::Winding, Transform::identity(), None);
    }
}

pub fn stroke_rounded_rect(
    pix: &mut Pixmap,
    x: f32,
    y: f32,
    w: f32,
    h: f32,
    r: f32,
    col: [u8; 4],
    width: f32,
) {
    if let Some(path) = rounded_rect_path(x, y, w, h, r) {
        let stroke = Stroke {
            width,
            ..Stroke::default()
        };
        pix.stroke_path(&path, &paint_rgba(col), &stroke, Transform::identity(), None);
    }
}

/// Alpha-composites a premultiplied `tiny-skia::Pixmap` onto a `softbuffer` `0x00RRGGBB` buffer.
pub fn blit_pixmap(buf: &mut [u32], buf_w: i32, buf_h: i32, pix: &Pixmap, dst_x: i32, dst_y: i32) {
    blit_pixmap_clipped(buf, buf_w, buf_h, pix, dst_x, dst_y, 0, 0, buf_w, buf_h);
}

/// Alpha-composites `pix` at `(dst_x, dst_y)` clipped to `[clip_x0..clip_x1, clip_y0..clip_y1)`.
#[allow(clippy::too_many_arguments)]
pub fn blit_pixmap_clipped(
    buf: &mut [u32],
    buf_w: i32,
    buf_h: i32,
    pix: &Pixmap,
    dst_x: i32,
    dst_y: i32,
    clip_x0: i32,
    clip_y0: i32,
    clip_x1: i32,
    clip_y1: i32,
) {
    let pw = pix.width() as i32;
    let ph = pix.height() as i32;
    let data = pix.data();

    let min_x = dst_x.max(clip_x0).max(0);
    let max_x = (dst_x + pw).min(clip_x1).min(buf_w);
    let min_y = dst_y.max(clip_y0).max(0);
    let max_y = (dst_y + ph).min(clip_y1).min(buf_h);
    if min_x >= max_x || min_y >= max_y {
        return;
    }

    for ty in min_y..max_y {
        let py = ty - dst_y;
        let row_dst = ty as usize * buf_w as usize;
        let row_src = py as usize * pw as usize * 4;

        for tx in min_x..max_x {
            let px = tx - dst_x;
            let si = row_src + px as usize * 4;
            let a = data[si + 3] as u32;
            if a == 0 {
                continue;
            }
            let sr = data[si] as u32;
            let sg = data[si + 1] as u32;
            let sb = data[si + 2] as u32;

            let dst_idx = row_dst + tx as usize;
            if a == 255 {
                buf[dst_idx] = (sr << 16) | (sg << 8) | sb;
            } else {
                let inv_a = 255 - a;
                let d = buf[dst_idx];
                let dr = (d >> 16) & 0xFF;
                let dg = (d >> 8) & 0xFF;
                let db = d & 0xFF;
                let out_r = (sr + ((dr * inv_a) >> 8)).min(255);
                let out_g = (sg + ((dg * inv_a) >> 8)).min(255);
                let out_b = (sb + ((db * inv_a) >> 8)).min(255);
                buf[dst_idx] = (out_r << 16) | (out_g << 8) | out_b;
            }
        }
    }
}

/// Crisp 5x7 bitmap font renderer with zero external font files or shaping overhead.
pub fn draw_bitmap_text(
    pix: &mut Pixmap,
    text: &str,
    start_x: i32,
    start_y: i32,
    scale: i32,
    col: [u8; 4],
) {
    let paint = paint_rgba(col);
    for (idx, ch) in text.chars().enumerate() {
        let glyph = glyph_5x7(ch);
        let gx = start_x + idx as i32 * 6 * scale;
        for (row, bits) in glyph.iter().enumerate() {
            for bit in 0..5 {
                if (bits >> (4 - bit)) & 1 == 1 {
                    let px = (gx + bit * scale) as f32;
                    let py = (start_y + row as i32 * scale) as f32;
                    if let Some(rc) = Rect::from_xywh(px, py, scale as f32, scale as f32) {
                        pix.fill_rect(rc, &paint, Transform::identity(), None);
                    }
                }
            }
        }
    }
}

pub fn text_pixel_width(text: &str, scale: i32) -> i32 {
    if text.is_empty() {
        0
    } else {
        (text.chars().count() as i32 * 6 - 1) * scale
    }
}

